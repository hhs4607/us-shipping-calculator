// Build nested rates structure: {origin: {size: {dest: yen}}}
function buildRates() {
  const rates = {};
  for (const origin of REGION_IDS) {
    const matrix = RAW_RATES[origin];
    if (!matrix || matrix.length !== SIZES.length) {
      throw new Error(`Bad matrix for origin ${origin}: ${matrix?.length}`);
    }
    rates[origin] = {};
    for (let i = 0; i < SIZES.length; i++) {
      const row = matrix[i];
      if (row.length !== REGION_IDS.length) {
        throw new Error(`Bad row ${SIZES[i]} for ${origin}: ${row.length} cols`);
      }
      const sizeKey = String(SIZES[i]);
      rates[origin][sizeKey] = {};
      for (let j = 0; j < REGION_IDS.length; j++) {
        rates[origin][sizeKey][REGION_IDS[j]] = row[j];
      }
    }
  }
  return rates;
}

function main() {
  const rates = buildRates();
  const outDir = path.join(__dirname, 'public', 'data', '2025', 'sagawa');
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, 'rates.json'),
    JSON.stringify(rates, null, 2) + '\n'
  );
  const totalCells = REGION_IDS.length * SIZES.length * REGION_IDS.length;
  console.log(`✓ Wrote rates.json with ${totalCells} cells (${REGION_IDS.length} origins × ${SIZES.length} sizes × ${REGION_IDS.length} dests)`);
}

if (require.main === module) main();

module.exports = { REGION_IDS, SIZES, RAW_RATES, buildRates };
